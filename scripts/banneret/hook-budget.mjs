#!/usr/bin/env node
// Banneret Hub: counts the lines we changed in upstream T3 Code files, against the upstream tag in
// scripts/banneret/UPSTREAM_TAG. New behaviour belongs in new files; upstream files get only
// one-line hooks, so this number should stay small. Fails when it grows past the baseline.
//   node scripts/banneret/hook-budget.mjs            # check
//   node scripts/banneret/hook-budget.mjs --update   # accept the current totals as the baseline
// Needs the upstream tag fetched into refs/upstream-tags/ (see docs/banneret/maintaining.md).
import * as NodeChildProcess from "node:child_process";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

// Upstream files we overwrite or regenerate on purpose; they never count.
const excluded = [
  /^assets\/(prod|nightly|dev)\//, // brand icons, from generate-icons.mjs
  /^apps\/web\/public\/.*\.(png|ico|svg|jpe?g|webp)$/, // brand icons, from generate-icons.mjs
  /^\.github\/workflows\/banneret-/,
  /^docs\/banneret\//,
  /^scripts\/banneret\//,
  /(^|\/)(pnpm-lock\.yaml|package-lock\.json|yarn\.lock|bun\.lockb?|Cargo\.lock)$/,
  /^apps\/web\/src\/routeTree\.gen\.ts$/, // generated by the TanStack router plugin
];

const repoRoot = NodePath.resolve(
  NodePath.dirname(NodeURL.fileURLToPath(import.meta.url)),
  "../..",
);
const baselinePath = NodePath.join(repoRoot, "scripts/banneret/hook-budget.json");
const tag = NodeFS.readFileSync(
  NodePath.join(repoRoot, "scripts/banneret/UPSTREAM_TAG"),
  "utf8",
).trim();
const upstreamRef = `refs/upstream-tags/${tag}`;

const git = (args) =>
  NodeChildProcess.execFileSync("git", args, {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });

try {
  git(["rev-parse", "--verify", "--quiet", `${upstreamRef}^{tree}`]);
} catch {
  console.error(`Missing ${upstreamRef}. Fetch it first:`);
  console.error(
    `  git fetch --no-tags https://github.com/pingdotgg/t3code.git '+refs/tags/${tag}:${upstreamRef}'`,
  );
  process.exit(1);
}

const upstreamFiles = new Set(
  git(["ls-tree", "-r", "-z", "--name-only", upstreamRef]).split("\0").filter(Boolean),
);

// -z numstat: "<added>\t<deleted>\t<path>\0"; binary files report "-" for both counts.
const rows = git(["diff", "--numstat", "-z", "--no-renames", upstreamRef, "HEAD"])
  .split("\0")
  .filter(Boolean)
  .map((entry) => {
    const [added, deleted, ...rest] = entry.split("\t");
    return {
      file: rest.join("\t"),
      added: added === "-" ? null : Number(added),
      deleted: deleted === "-" ? null : Number(deleted),
    };
  })
  .filter(({ file }) => upstreamFiles.has(file) && !excluded.some((regex) => regex.test(file)))
  .sort((a, b) => a.file.localeCompare(b.file));

const totals = {
  files: rows.length,
  lines: rows.reduce((sum, row) => sum + (row.added ?? 0) + (row.deleted ?? 0), 0),
};

const show = (count) => (count === null ? "bin" : String(count));
const width = Math.max(4, ...rows.map((row) => row.file.length));
console.log(`Upstream files changed since ${tag}:`);
console.log(`${"file".padEnd(width)}  ${"+".padStart(5)}  ${"-".padStart(5)}`);
for (const row of rows) {
  console.log(
    `${row.file.padEnd(width)}  ${show(row.added).padStart(5)}  ${show(row.deleted).padStart(5)}`,
  );
}
console.log(`total: ${totals.files} files touched, ${totals.lines} lines changed`);

if (process.argv.includes("--update")) {
  NodeFS.writeFileSync(baselinePath, `${JSON.stringify(totals, null, 2)}\n`);
  console.log(`baseline: ${totals.files} files, ${totals.lines} lines`);
  process.exit(0);
}

const baseline = JSON.parse(NodeFS.readFileSync(baselinePath, "utf8"));
const over = ["files", "lines"].filter((key) => totals[key] > baseline[key]);
if (over.length > 0) {
  console.error(
    `Hook budget exceeded (baseline: ${baseline.files} files, ${baseline.lines} lines). ` +
      "Move the new behaviour into new files, or review the growth and run with --update.",
  );
  process.exit(1);
}
console.log(`hook budget passed (baseline: ${baseline.files} files, ${baseline.lines} lines)`);
